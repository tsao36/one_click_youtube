REMOTION_DIR = ROOT / "remotion-video"
OUTPUT_DIR = REMOTION_DIR / "out" / "renders"
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)


def get_preset_props(preset_name: str, **kwargs) -> Dict[str, Any]:
    """Retrieve default props for standard presets from TypeScript definitions or synthetic generator."""
    if preset_name == "WifiAssociationScene":
        return _make_wifi_association_props()
    elif preset_name == "Wifi7MloStrScene":
        return _make_wifi7_mlo_props(mode="str")
    elif preset_name == "Wifi7MloeMlsrScene":
        return _make_wifi7_mlo_props(mode="emlsr")
    elif preset_name == "BleLifecycleScene":
        return _make_ble_lifecycle_props()
    elif preset_name in ("WirelessCoexistenceScene", "WirelessNetworkScene"):
        return _make_coexistence_master_props(**kwargs)
    raise ValueError(f"Unknown wireless preset: {preset_name}")


def render_wireless_scene(
    composition: str,
    props: Dict[str, Any],
    out_mp4_path: Path | str,
    duration_frames: int,
    fps: int = 30,
    dim: float = 0.75,
    use_gpu_gl: bool = True,
    timeout: int = 600,
) -> Path:
    """Render a wireless protocol animation composition to MP4."""
    out_path = Path(out_mp4_path).resolve()
    out_path.parent.mkdir(parents=True, exist_ok=True)

    # Validate props with Pydantic model
    validated = WirelessSceneProps.model_validate(props)
    clean_props = validated.model_dump(by_alias=True)

    log.info(
        "Rendering Wireless Scene '%s' to '%s' (%d frames @ %d fps)",
        composition,
        out_path.name,
        duration_frames,
        fps,
    )

    return render_composition(
        remotion_dir=REMOTION_DIR,
        composition=composition,
        props=clean_props,
        out_path=out_path,
        frames=duration_frames,
        dim=dim,
        use_gpu_gl=use_gpu_gl,
        timeout=timeout,
    )


